import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Build only after Vite. Exported for temporary-directory build tests. */
export async function buildPwa(dist = resolve('dist')) {
  const files = [];
  async function visit(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile() && relative(dist, path) !== 'sw.js') files.push(path);
    }
  }
  await visit(dist);
  files.sort();
  if (!files.includes(join(dist, 'index.html')))
    throw new Error('Build Vite first: dist/index.html is missing.');
  const hash = createHash('sha256');
  const paths = [];
  for (const file of files) {
    const path = relative(dist, file).split(sep).join('/');
    const bytes = await readFile(file);
    hash.update(JSON.stringify([path, bytes.length])).update(bytes);
    paths.push(path.split('/').map(encodeURIComponent).join('/'));
  }
  const version = hash.digest('hex').slice(0, 24);
  const source = `/* Generated by tools/build-pwa.mjs. No game/save state is stored here. */
const VERSION = ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(paths)};
const SCOPE = new URL(self.registration.scope);
const PREFIX = 'mana-crystals:' + encodeURIComponent(SCOPE.href) + ':';
const CACHE = PREFIX + VERSION;
const INDEX = new URL('index.html', SCOPE).href;
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(
    PRECACHE.map((path) => new Request(new URL(path, SCOPE).href, { cache: 'reload' }))
  )));
});
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key))
  )));
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  const network = fetch(request);
  // Keep successful updates alive independently of the response promise.
  event.waitUntil(network.then(async (response) => {
    if (response.ok && response.type !== 'opaque' && !response.redirected) {
      const copy = response.clone();
      const cache = await caches.open(CACHE);
      await cache.put(request, copy);
    }
  }).catch(() => {}));
  event.respondWith((async () => {
    try {
      return await network;
    } catch {
      const cache = await caches.open(CACHE);
      const cached = await cache.match(request);
      if (cached) return cached;
      if (request.mode === 'navigate') {
        const index = await cache.match(INDEX);
        if (index) return index;
      }
      return Response.error();
    }
  })());
});
`;
  await writeFile(join(dist, 'sw.js'), source);
  return { version, files: paths };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildPwa(process.argv[2] ? resolve(process.argv[2]) : resolve('dist'));
}
