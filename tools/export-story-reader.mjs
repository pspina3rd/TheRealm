#!/usr/bin/env node
// Review export only. This never writes game text, saves or the hand-edited bible.
import { createServer } from 'vite';
import { format } from 'prettier';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sources = [
  'src/data/story.ts',
  'src/data/campaignStory.ts',
  'src/data/npcs.ts',
  'src/data/campaignNpcs.ts',
  'src/data/mentors.ts',
  'src/data/hometowns.ts',
  'src/data/classes.ts',
];
const hash = (text) => createHash('sha256').update(text).digest('hex');
const sourceHashes = Object.fromEntries(
  sources.map((path) => [path, hash(readFileSync(resolve(root, path)))]),
);
const fingerprint = hash(JSON.stringify(sourceHashes));
const lines = [];
const passageIds = new Set();
let quotes = 0;
let suppressed = 0;
const add = (...text) => lines.push(...text);
function passage(id, value, context = '') {
  if (passageIds.has(id)) throw new Error(`Duplicate reader passage: ${id}`);
  passageIds.add(id);
  add(`#### ${id}`, '');
  if (context) add(context, '');
  if (value === '') add('*Empty source string: no words in this variant.*', '');
  else {
    add(...value.split('\n').map((line) => `> ${line}`), '');
    quotes++;
  }
}
function variants(id, value, options = {}) {
  if (typeof value === 'string') {
    if (options.unsaid?.includes(value)) {
      suppressed++;
      return;
    }
    const until = options.saidUntil?.lines.includes(value)
      ? `Available only before \`${options.saidUntil.flag}\`.`
      : '';
    passage(id, value, until);
  } else if (Array.isArray(value)) {
    value.forEach((text, i) => variants(`${id}.${String(i + 1).padStart(2, '0')}`, text, options));
  } else if (value && typeof value === 'object') {
    for (const [key, text] of Object.entries(value)) variants(`${id}.${key}`, text, options);
  }
}

const server = await createServer({ root, server: { middlewareMode: true } });
try {
  const story = await server.ssrLoadModule('/src/data/story.ts');
  const { NPCS } = await server.ssrLoadModule('/src/data/npcs.ts');
  const { CAMPAIGN_SPEAKERS, CAMPAIGN_NPCS } = await server.ssrLoadModule(
    '/src/data/campaignNpcs.ts',
  );
  const { MENTORS } = await server.ssrLoadModule('/src/data/mentors.ts');
  const { CLASSES } = await server.ssrLoadModule('/src/data/classes.ts');
  const names = {
    hero: 'Chosen hero',
    master: 'The voice',
    vesperDuel: 'Vesper',
    irdrath: 'Irdrath',
    lishal: 'The Lishal',
    worker: 'Worker',
    courier: 'Courier',
    moonWyrm: 'Moon Wyrm',
    ...Object.fromEntries(Object.entries(NPCS).map(([id, npc]) => [id, npc.name])),
    ...Object.fromEntries(Object.entries(MENTORS).map(([id, mentor]) => [id, mentor.name])),
    ...Object.fromEntries(Object.entries(CAMPAIGN_SPEAKERS).map(([id, actor]) => [id, actor.name])),
  };
  add(
    '# Mana Crystals — Story Reader',
    '',
    '**Current game text for wording review · full-story spoilers**',
    '',
    'Read with the [World Bible](WORLD_BIBLE.md). This companion preserves the source',
    'words; it does not approve proposed lore or rewrite awkward phrasing.',
    '',
    `Source fingerprint: \`${fingerprint}\`.`,
    '',
    '## How to review',
    '',
    '- Cite the printed passage ID when suggesting a change. Scene IDs follow the actual game data.',
    '- Directions and line fields are separated. Some directions contain quoted speech; scene staging determines how it is presented.',
    '- Class alternatives, attitude branches and optional-mentor conditions are shown together for reference; one playthrough does not show every version.',
    '- Raw hometown wording is preserved. The runtime substitutes the chosen home where applicable; literal navigation is separate.',
    '- NPC variants marked as permanently suppressed are excluded. A conditional line is labeled with the flag after which it stops being available.',
    '- The corpus covers main interludes, visions, boss preludes, Vesper, NPC conversation branches and mentor dialogue. It is not an export of every menu, puzzle instruction or item description.',
    '- The source scene array provides reading order. Quest gates and optional conversations determine the actual order during play.',
    '- All continuation lore remains proposed where identified in the bible, even when these words already appear in the playable adaptation.',
    '',
    'The Markdown reader is generated by `node tools/export-story-reader.mjs`.',
    'The companion manifest records source and output hashes. `--check` detects stale exports.',
    'Keep annotated review copies before regenerating; the exporter never imports edits into the game.',
    '',
    '## Main story scenes',
    '',
  );
  let beatCount = 0;
  const sceneIds = [];
  for (const scene of story.SCENES) {
    if (sceneIds.includes(scene.id)) throw new Error(`Duplicate scene: ${scene.id}`);
    sceneIds.push(scene.id);
    add(
      `### ${scene.title} [${scene.id}]`,
      '',
      `Source: [${story.CHAPTER_ONE_SCENES.includes(scene) ? 'story.ts' : 'campaignStory.ts'}](../src/data/${story.CHAPTER_ONE_SCENES.includes(scene) ? 'story' : 'campaignStory'}.ts).`,
      '',
    );
    for (const [index, beat] of scene.beats.entries()) {
      beatCount++;
      const id = `SR-${scene.id}-${String(index + 1).padStart(2, '0')}`;
      add(`#### ${id}`, '');
      if (beat.requiresMentor)
        add(
          `Conditional mentor contribution: **${names[beat.requiresMentor] ?? beat.requiresMentor}**.`,
          '',
        );
      if (beat.gives) add(`Item handover in source: \`${beat.gives}\`.`, '');
      if (beat.stage) {
        add('**Presentation direction**', '', ...beat.stage.split('\n').map((v) => `> ${v}`), '');
        quotes++;
      }
      if (beat.line !== undefined) {
        add(
          `**${names[beat.who] ?? beat.who ?? 'Speaker supplied by scene staging'}**`,
          '',
          ...beat.line.split('\n').map((v) => `> ${v}`),
          '',
        );
        quotes++;
      }
      if (beat.classLines)
        for (const [classId, text] of Object.entries(beat.classLines)) {
          const hero = CLASSES[classId];
          add(
            `**${hero?.heroName ?? classId} · ${hero?.name ?? classId} alternative**`,
            '',
            ...text.split('\n').map((v) => `> ${v}`),
            '',
          );
          quotes++;
        }
      if (passageIds.has(id)) throw new Error(`Duplicate passage: ${id}`);
      passageIds.add(id);
    }
  }
  add('## Visions and confrontation preludes', '');
  for (const vision of story.VISIONS) {
    add(`### ${vision.id}`, '');
    variants(`SR-${vision.id}`, vision.lines);
  }
  for (const [id, text] of Object.entries(story.PRELUDES)) {
    add(`### ${names[id] ?? id} · before combat`, '');
    variants(`SR-prelude-${id}`, text);
  }
  add('### The ward after the Wyrm', '');
  variants('SR-ward-after-wyrm', story.WARD_AFTER_WYRM);
  add(
    '## Vesper — recurring conversation branches',
    '',
    'Shared by the road, quarry, peaks and ruins appearances. Cold means Hostile/Wary;',
    'plain means Neutral; warm means Friendly/Devoted. Availability also depends',
    'on the moment and its relationship gate.',
    '',
  );
  variants('SR-vesper', story.VESPER_LINES);
  add(
    '## Residents — conversation branches',
    '',
    'These are branch texts, not one continuous conversation. The moment and mood',
    'are part of each passage ID. Some source names include a task label.',
    '',
  );
  for (const [id, npc] of Object.entries(NPCS).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    if (id.startsWith('vesper')) continue;
    add(
      `### ${npc.name} [${id}]`,
      '',
      `Source: [${id in CAMPAIGN_NPCS ? 'campaignNpcs.ts' : 'npcs.ts'}](../src/data/${id in CAMPAIGN_NPCS ? 'campaignNpcs' : 'npcs'}.ts).`,
      '',
    );
    variants(`SR-npc-${id}`, npc.lines, { unsaid: npc.unsaid, saidUntil: npc.saidUntil });
  }
  add(
    '## Mentors — teaching and relationship dialogue',
    '',
    'These texts include greetings, wins/losses, arrivals, seeking, after-lesson',
    'responses and Road Back contributions. Conditional relationship text must not',
    'be treated as a friendship earned by every hero.',
    '',
  );
  for (const mentor of Object.values(MENTORS)) {
    add(
      `### ${mentor.name} [${mentor.id}]`,
      '',
      'Source: [mentors.ts](../src/data/mentors.ts).',
      '',
    );
    for (const field of [
      'motive',
      'winText',
      'loseText',
      'arrives',
      'seeks',
      'afterLesson',
      'failedLesson',
      'roadBack',
    ]) {
      add(`**${field}**`, '');
      variants(`SR-mentor-${mentor.id}.${field}`, mentor[field]);
    }
  }
  add(
    '## Review scope and authority',
    '',
    'This export keeps the source language intact. A source string can still need',
    'editing, clearer staging or an author decision about canon. The World Bible',
    'separates those decisions from implementation. Reviewing this reader does not',
    'silently approve every proposed relationship, mechanism or ending.',
    '',
  );
  const output = await format(lines.join('\n'), { parser: 'markdown', proseWrap: 'preserve' });
  const manifest = {
    formatVersion: 1,
    sourceFingerprint: fingerprint,
    sourceHashes,
    scenes: sceneIds,
    sceneCount: sceneIds.length,
    beatCount,
    passageCount: passageIds.size,
    textBlocks: quotes,
    permanentlySuppressedVariants: suppressed,
    readerSha256: hash(output),
  };
  const target = resolve(root, 'docs/WORLD_BIBLE_STORY_READER.md');
  const manifestTarget = resolve(root, 'docs/WORLD_BIBLE_STORY_READER.manifest.json');
  const metadata = JSON.stringify(manifest, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    if (
      readFileSync(target, 'utf8') !== output ||
      readFileSync(manifestTarget, 'utf8') !== metadata
    )
      throw new Error(
        'Story Reader is stale; regenerate it and preserve any annotated author copy.',
      );
  } else {
    writeFileSync(target, output);
    writeFileSync(manifestTarget, metadata);
  }
  process.stdout.write(
    `${process.argv.includes('--check') ? 'Verified' : 'Exported'} ${manifest.sceneCount} scenes, ${beatCount} beats and ${manifest.passageCount} review passages.\n`,
  );
} finally {
  await server.close();
}
