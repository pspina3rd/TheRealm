import { rolldown } from 'rolldown';
import { mkdir, writeFile } from 'node:fs/promises';
const directory = 'ios/ManaCrystalsPlaytest/Engine';
await mkdir(directory, { recursive: true });
const bundle = await rolldown({ input: 'src/nativeApp.ts', platform: 'neutral' });
try {
  const { output } = await bundle.generate({
    format: 'iife',
    name: 'ManaCrystalsNative',
    minify: true,
  });
  const code = output.find((item) => item.type === 'chunk')?.code;
  if (!code) throw new Error('Native engine bundle was empty.');
  await writeFile(
    `${directory}/battle-engine.js`,
    '// Generated by npm run build:native. Production rules, bundled for JavaScriptCore.\n' + code,
  );
  process.stdout.write('Bundled the production battle engine for the native iOS playtest.\n');
} finally {
  await bundle.close();
}
